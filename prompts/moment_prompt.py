def build_roster_block(characters: list[dict]) -> str:
    """Render the cast roster that gets prepended to the chapter text."""
    if not characters:
        return (
            "CAST ROSTER: (empty — no characters established yet, so every "
            "named significant person belongs under NEW_CHARACTERS)"
        )
    lines = ["CAST ROSTER:"]
    for c in characters:
        lines.append(f"- {c['id']} | {c['name']}: {c['identity']}")
        if c.get("default_outfit"):
            # How they dress, so an inferred outfit stays in character.
            lines.append(f"    usually dresses: {c['default_outfit']}")
    return "\n".join(lines)


